// Build and write the addon's Generated/Entries.lua from all character states.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { CharacterState } from "./store.js";
import { toLua, writeFileAtomic } from "../savedvars/serialize.js";
import { normalizeBody } from "../llm/write.js";

export function loadAllStates(dataDir: string): CharacterState[] {
  if (!existsSync(dataDir)) return [];
  return readdirSync(dataDir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => JSON.parse(readFileSync(join(dataDir, f), "utf8")) as CharacterState);
}

export function renderGenerated(states: CharacterState[], now = Math.floor(Date.now() / 1000)): string {
  const characters: Record<string, unknown> = {};
  for (const s of states) {
    characters[s.charKey] = {
      processedThrough: s.processedThrough,
      entries: s.entries.map((e) => ({
        id: e.id,
        day: e.day,
        dayEnd: e.dayEnd !== e.day ? e.dayEnd : undefined,
        title: e.title,
        body: normalizeBody(e.body),
        zone: e.zone,
        subzone: e.subzone,
        restKind: e.restKind,
        level: e.level,
        t: e.t,
        prompt: e.prompt,
      })),
    };
  }
  const data = { version: 1, generatedAt: now, characters };
  return [
    "-- GENERATED BY THE QUILL & HEARTH COMPANION APP. DO NOT EDIT.",
    `QuillAndHearth_Generated = ${toLua(data)}`,
    "",
  ].join("\n");
}

export function writeGenerated(addonDir: string, states: CharacterState[]): string {
  const path = join(addonDir, "Generated", "Entries.lua");
  writeFileAtomic(path, renderGenerated(states));
  return path;
}
